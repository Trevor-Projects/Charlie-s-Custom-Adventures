/** Get the minimum XP needed to attain a specific level */
export function getXpRequiredForLevel(level: number): number {
  const targetLevel = Math.max(1, Math.min(20, level));
  return LEVEL_XP_THRESHOLDS[targetLevel] ?? 0;
}

/** Compute the XP progression progress between current level and next level */
export function getXpProgressInfo(xp: number = 0, currentLevel: number = 1) {
  const currentFloor = LEVEL_XP_THRESHOLDS[currentLevel] || 0;
  const nextTarget = LEVEL_XP_THRESHOLDS[Math.min(20, currentLevel + 1)] || currentFloor;
  const isMaxLevel = currentLevel >= 20;

  if (isMaxLevel) {
    return {
      currentXp: xp,
      currentLevelFloor: currentFloor,
      nextLevelTarget: currentFloor,
      xpInCurrentBracket: 0,
      xpNeededInBracket: 0,
      xpToNextLevel: 0,
      percent: 100,
      canLevelUp: false,
    };
  }

  const xpNeededInBracket = Math.max(1, nextTarget - currentFloor);
  const xpInCurrentBracket = Math.max(0, xp - currentFloor);
  const xpToNextLevel = Math.max(0, nextTarget - xp);
  const percent = Math.min(100, Math.max(0, Math.round((xpInCurrentBracket / xpNeededInBracket) * 100)));
  const canLevelUp = xp >= nextTarget;

  return {
    currentXp: xp,
    currentLevelFloor: currentFloor,
    nextLevelTarget: nextTarget,
    xpInCurrentBracket,
    xpNeededInBracket,
    xpToNextLevel,
    percent,
    canLevelUp,
  };
}

