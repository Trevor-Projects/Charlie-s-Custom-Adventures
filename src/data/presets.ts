export function generateRandomName(
  characterClass: CharacterClass,
  race: Race,
  existingNames: string[] = []
): string {
  const pool = NAME_POOL[race] || NAME_POOL.Human;
  const lowerExisting = existingNames.map((n) => n.trim().toLowerCase());

  // Filter pool for unused names
  const available = pool.filter((n) => !lowerExisting.includes(n.toLowerCase()));
  if (available.length > 0) {
    return available[Math.floor(Math.random() * available.length)];
  }

  // If pool runs low, append unique title/surname
  const epithets = ['Stormweaver', 'Ironhand', 'Shadowwalker', 'the Bold', 'Lightbringer', 'Vanguard', 'Spellweaver', 'Shieldbearer', 'the Brave', 'Frostblade', 'the Undaunted', 'Starcaller'];
  for (let i = 0; i < 50; i++) {
    const base = pool[Math.floor(Math.random() * pool.length)];
    const ep = epithets[Math.floor(Math.random() * epithets.length)];
    const candidate = `${base} ${ep}`;
    if (!lowerExisting.includes(candidate.toLowerCase())) {
      return candidate;
    }
  }

  return `${pool[0]} ${Math.floor(Math.random() * 900 + 100)}`;
}

