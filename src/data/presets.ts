/** Generates a high-quality, guaranteed unique 3-5 sentence fantasy backstory based on class, race, name, and gender pronouns */
export function generateFantasyBackstory(
  name: string,
  race: Race,
  characterClass: CharacterClass,
  existingBackstories: string[] = [],
  gender: Gender = "I'd rather not say"
): string {
  const p = getPronouns(gender);
  const lowerExisting = existingBackstories.map((b) => b.trim().toLowerCase());

  const origins = [
    `Raised in the mist-shrouded borderlands of the ancient realms, ${name} inherited the unyielding resilience of ${p.possessiveAdj} ${race} lineage.`,
    `Hailing from the high spires of an elder citadel, ${name} was steeped in the solemn traditions and forgotten lore of the ${race} elders.`,
    `Schooled in the perilous frontier outposts where civilization fades into wild myth, ${name} learned early that a ${race}'s sharp instincts mean the difference between life and death.`,
    `Born under a blood-red moon during a fierce mountain siege, ${name} carried the mark of destiny long before taking up arms as a ${characterClass}.`,
    `Trained in secret sanctuaries nestled deep within the primordial forests, ${name} earned a revered place among ${p.possessiveAdj} ${race} clan.`,
    `Abandoned as an infant near the whispering ruins of an ancient arcane temple, ${name} was fostered by veteran ${race} guardians.`,
    `Growing up in the bustling harbor districts of a coastal metropolis, ${name} developed a razor-sharp survival instinct and a thirst for high adventure.`,
    `Deep in the subterranean caverns where light never penetrates, ${name} forged ${p.possessiveAdj} willpower amidst molten stone and dark magic.`,
  ];

  const turningPoints = [
    `When an ancient shadow shattered the tranquility of ${p.possessiveAdj} homeland, ${name} pledged ${p.possessiveAdj} weapon as a ${characterClass} to defend the helpless.`,
    `After discovering a cryptic heirloom inscribed with forbidden runes, ${name} embarked on a quest to uncover ${p.possessiveAdj} family's true purpose.`,
    `Tempered by years of wandering through forgotten ruins and fighting off subterranean horrors, ${p.subject} mastered the deadly art of the ${characterClass}.`,
    `Bound by a solemn oath sworn before the altar of ${p.possessiveAdj} ancestors, ${name} set out to hunt down the fell forces threatening the realm.`,
    `Having survived a treacherous betrayal by a rival merchant house, ${name} forged a new identity bound to honor, blade, and magic.`,
    `When a dragon's flame scorched ${p.possessiveAdj} ancestral guildhall, ${name} vowed never again to stand idle while innocent blood is spilled.`,
    `Inspired by the heroic sagas told by traveling bards, ${name} left behind a quiet farmstead to carve out a legacy worthy of legend.`,
    `After unlocking a long-dormant magical lineage during an unexpected demonic breach, ${name} accepted ${p.possessiveAdj} calling as a ${characterClass}.`,
  ];

  const traits = [
    `Guided by an unshakeable moral compass and a quick wit, ${name} approaches every conflict with tactical precision and unyielding resolve.`,
    `Equipped with battle-tested armor and an acute sense for ambush, ${p.subject} walks with a quiet, lethal grace that inspires allies and unnerves foes alike.`,
    `With a deep reverence for the sacred balance of the world, ${name} brings both veteran combat skill and strategic wisdom to the party.`,
    `Known across the taverns and keeps as a fearless defender, ${name} never backs down from a threat to those in ${p.possessiveAdj} care.`,
    `Possessing a mind that analyzes combat as a grand chess game, ${name} turns even the direst odds into calculated victories.`,
    `Infused with fierce loyalty toward companions, ${name} will cross rivers of fire before letting a comrade fall.`,
    `Quietly observant yet devastatingly decisive in crisis, ${name} balances ancient lore with practical battle prowess.`,
  ];

  const destinies = [
    `Now, drawn by rumors of ancient artifacts and rising darkness, ${name} journeys forward to etch ${p.possessiveAdj} name into the legends of the continent.`,
    `Driven by a thirst for truth and glory, ${name} stands ready to confront whatever dragon, fiend, or tyrant blocks the path ahead.`,
    `With fate calling ${p.object} toward uncharted frontiers, ${name} answers the call to adventure without a shadow of hesitation.`,
    `Bound to a grand destiny foretold in ancient sagas, ${name} fights to restore peace and usher in a new age of heroes.`,
    `Determined to unravel the cosmic mystery behind ${p.possessiveAdj} lineage, ${name} marches into the storm with blade in hand.`,
    `Seeking to rebuild a fallen order of protectors, ${name} travels the shattered roads of the realm in search of worthy allies.`,
    `Pushed forward by the memory of lost loved ones, ${name} swears to be the wall that stands between light and darkness.`,
  ];

  for (let attempt = 0; attempt < 100; attempt++) {
    const origin = origins[Math.floor(Math.random() * origins.length)];
    const point = turningPoints[Math.floor(Math.random() * turningPoints.length)];
    const trait = traits[Math.floor(Math.random() * traits.length)];
    const destiny = destinies[Math.floor(Math.random() * destinies.length)];

    const candidate = `${origin} ${point} ${trait} ${destiny}`;
    if (!lowerExisting.includes(candidate.trim().toLowerCase())) {
      return candidate;
    }
  }

  // Fallback if thousands of backstories exist
  const origin = origins[Math.floor(Math.random() * origins.length)];
  const point = turningPoints[Math.floor(Math.random() * turningPoints.length)];
  const trait = traits[Math.floor(Math.random() * traits.length)];
  const destiny = destinies[Math.floor(Math.random() * destinies.length)];
  return `${origin} ${point} ${trait} ${destiny} Sealed by sacred oath #${Math.floor(Math.random() * 899 + 100)}.`;
}

export const SPELLCASTING_CLASSES: CharacterClass[] = [
  'Wizard',
  'Cleric',
  'Bard',
  'Sorcerer',
  'Warlock',
  'Druid',
  'Paladin',
  'Ranger',
];

export function getSpellSlotsForClass(characterClass: CharacterClass, level: number = 1): number {
  if (['Wizard', 'Cleric', 'Bard', 'Sorcerer', 'Druid'].includes(characterClass)) {
    if (level >= 3) return 4;
    if (level === 2) return 3;
    return 2;
  }
  if (characterClass === 'Warlock') {
    if (level >= 2) return 2;
    return 1;
  }
  if (['Paladin', 'Ranger'].includes(characterClass)) {
    if (level >= 2) return 2;
    return 0;
  }
  return 0;
}

export function randomizeCharacter(
  existingChar: Character,
  playerNumber: number,
  existingNames: string[] = [],
  existingBackstories: string[] = []
): Character {
  const genders: Gender[] = ['Male', 'Female', "I'd rather not say"];
  const gender = existingChar?.gender || genders[Math.floor(Math.random() * genders.length)];
  const randomClass = ALL_CLASSES[Math.floor(Math.random() * ALL_CLASSES.length)];
  const randomRace = ALL_RACES[Math.floor(Math.random() * ALL_RACES.length)];
  const newName = generateRandomName(randomClass, randomRace, existingNames);
  const newStats = rollDndStats();

  const hpByClass: Record<CharacterClass, number> = {
    Barbarian: 15,
    Fighter: 12,
    Paladin: 12,
    Ranger: 11,
    Cleric: 10,
    Druid: 10,
    Monk: 10,
    Rogue: 10,
    Bard: 10,
    Warlock: 10,
    Wizard: 8,
    Sorcerer: 8,
  };

  const acByClass: Record<CharacterClass, number> = {
    Fighter: 16,
    Paladin: 18,
    Barbarian: 14,
    Rogue: 14,
    Wizard: 12,
    Cleric: 16,
    Ranger: 15,
    Bard: 13,
    Warlock: 13,
    Sorcerer: 12,
    Druid: 13,
    Monk: 15,
  };

  const slots = getSpellSlotsForClass(randomClass, 1);

  const avatars: Record<CharacterClass, string> = {
    Fighter: '⚔️',
    Wizard: '🪄',
    Rogue: '🗡️',
    Cleric: '✨',
    Paladin: '🛡️',
    Barbarian: '🪓',
    Bard: '🪕',
    Ranger: '🏹',
    Warlock: '🔮',
    Sorcerer: '⚡',
    Druid: '🌿',
    Monk: '☯️',
  };

  const maxHp = hpByClass[randomClass];
  const backstory = generateFantasyBackstory(newName, randomRace, randomClass, existingBackstories, gender);

  return {
    ...existingChar,
    name: newName,
    gender,
    race: randomRace,
    characterClass: randomClass,
    maxHp,
    hp: maxHp,
    ac: acByClass[randomClass],
    stats: newStats,
    spellSlots: slots,
    maxSpellSlots: slots,
    backstory,
    avatar: avatars[randomClass],
    portraitUrl: getAutoGeneratedPortrait(randomRace, randomClass, newName, gender),
  };
}

